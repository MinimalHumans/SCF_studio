/**
 * emit_normative_data.mjs — publish the junction keys and the Q14
 * rubrics as files.
 *
 * Both are cited by MUSTs that a third party cannot otherwise satisfy:
 *
 *   §6.3  the natural key for each link entity. Cited
 *         as `junctionKeyFields()` — a function, not an artifact — a
 *         third party cannot compute a natural key, so it cannot
 *         de-duplicate, merge or validate a junction.
 *
 *   §12.9 Q14 assesses a target query against a rubric. The section
 *         defines the envelope and the severity scale; without the
 *         rubric a reader can only invent one, and correctly refuse to
 *         claim anything for it.
 *
 * Both are DERIVED facts, so both are emitted rather than written: the
 * junction keys from the registry's own reference declarations, the
 * rubrics from `QUERY_PATHS`. IF A MUST CITES SOMETHING, THAT SOMETHING
 * HAS TO BE A FILE.
 *
 *   node --experimental-strip-types scripts/emit_normative_data.mjs
 *   node --experimental-strip-types scripts/emit_normative_data.mjs --check
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadRegistry } from "../src/registry.ts";
import { junctionEntities, junctionKeyFields } from "../src/junctions.ts";
import { QUERY_PATHS } from "../src/queryPaths.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const SPEC = join(HERE, "..", "..", "spec");
const REGISTRY = join(HERE, "..", "registry", "registry.json");

const registry = loadRegistry(JSON.parse(readFileSync(REGISTRY, "utf8")));

// --- junction natural keys, spec §6.3 --------------------------------

const junctions = junctionEntities(registry)
  .map((e) => ({ entity: e.name, keyFields: junctionKeyFields(e) }))
  .sort((a, b) => a.entity.localeCompare(b.entity));

const junctionDoc = {
  $comment:
    "GENERATED by scf-core/scripts/emit_normative_data.mjs. The natural " +
    "key of each link entity, spec/scf-spec.md §6.3. A uuid identifies a " +
    "row within one file; a natural key identifies the same LINK across " +
    "files, and is what merging, de-duplicating and validating stand on.",
  specSection: "§6.3",
  schemaVersion: registry.schemaVersion,
  derivation:
    "Every non-auto-injected reference field the entity declares that is " +
    "not marked qualifier, then " +
    "entity_type, entity_id and domain where present. Derived from the " +
    "registry; not maintained by hand.",
  entityCount: junctions.length,
  entities: junctions,
};

// --- readiness rubrics, spec §12.9 -----------------------------------

// Every entity a step names must BE an entity. This is the check that
// makes §12.9.1's steps resolvable rather than readable: a typo, a
// renamed entity, or a return to prose fails the build instead of
// shipping a rubric a third party has to interpret.
// loadRegistry() returns entities as a Map keyed by name.
const registryEntities = registry.entities;
const unresolved = [];
for (const [id, path] of Object.entries(QUERY_PATHS)) {
  for (const s of path.steps) {
    for (const name of s.entities) {
      if (!registryEntities.has(name)) unresolved.push(`${id}: ${name}`);
    }
    // `satisfiedBy` is a subset of `entities`: the step's context names
    // a finding, and only an entity the step names can decide it.
    for (const name of s.satisfiedBy ?? []) {
      if (!s.entities.includes(name)) {
        unresolved.push(`${id}: satisfiedBy ${name} is not among the ` +
                        "step's entities");
      }
    }
    // An intent must be one the registry offers a bundle, or the media
    // step asks for references nothing can carry.
    const intents = registryEntities.get("bundle")?.fields
      .find((f) => f.name === "intent")?.options ?? [];
    for (const i of [s.intent, ...Object.values(s.intentBySubjectType ?? {})]) {
      if (i !== undefined && !intents.includes(i)) {
        unresolved.push(`${id}: intent ${i} is not a bundle intent`);
      }
    }
    if (s.intent !== undefined && s.intentBySubjectType !== undefined) {
      unresolved.push(`${id}: a step carries intent or ` +
                      "intentBySubjectType, not both");
    }
    // A step resolved by a query is resolved by a canonical one with a
    // rubric of its own, or the reader has no answer to count rows in.
    if (s.resolvedBy !== undefined && !(s.resolvedBy in QUERY_PATHS)) {
      unresolved.push(`${id}: resolvedBy ${s.resolvedBy} has no rubric`);
    }
    if (s.filter !== undefined) {
      // The filter column must exist on every entity the step names,
      // or the step describes a subset that cannot be taken.
      for (const name of s.entities) {
        const entity = registryEntities.get(name);
        const has = entity?.fields.some((f) => f.name === s.filter.field);
        if (!has) unresolved.push(`${id}: ${name} has no ${s.filter.field}`);
      }
    }
  }
}
if (unresolved.length > 0) {
  console.error("[normative-data] rubric steps do not resolve against the " +
                "registry:");
  for (const u of unresolved) console.error(`  ${u}`);
  process.exit(1);
}

const rubrics = Object.entries(QUERY_PATHS)
  .map(([id, path]) => ({
    query: id,
    name: path.name,
    params: path.params,
    description: path.description,
    steps: path.steps.map((s) => ({
      // `entities` is the machine-readable part and every name in it is
      // a registry entity, checked above. `label` is derived from it for
      // display and is the only prose here.
      entities: s.entities,
      ...(s.satisfiedBy === undefined ? {} : { satisfiedBy: s.satisfiedBy }),
      requirement: s.requirement,
      purpose: s.purpose,
      ...(s.filter === undefined ? {} : { filter: s.filter }),
      ...(s.intent === undefined ? {} : { intent: s.intent }),
      ...(s.intentBySubjectType === undefined
        ? {} : { intentBySubjectType: s.intentBySubjectType }),
      ...(s.appliesTo === undefined ? {} : { appliesTo: s.appliesTo }),
      ...(s.resolvedBy === undefined ? {} : { resolvedBy: s.resolvedBy }),
      label: s.label,
    })),
  }))
  .sort((a, b) => a.query.localeCompare(b.query));

const rubricDoc = {
  $comment:
    "GENERATED by scf-core/scripts/emit_normative_data.mjs. The rubric " +
    "Q14 assesses a target query against, spec/scf-spec.md §12.9. Each " +
    "step names an entity the target depends on and how much it depends " +
    "on it; a missing `required` step is a blocker, a missing " +
    "`recommended` step a warning, a missing `optional` step `ok` " +
    "unless its absence is notable at the position, then a " +
    "suggestion (§12.9.1), and a present step an `ok`.",
  specSection: "§12.9",
  schemaVersion: registry.schemaVersion,
  requirementToSeverity: {
    required: "blocker",
    recommended: "warning",
    optional: "suggestion",
    present: "ok",
  },
  $steps:
    "A step's `entities` are REGISTRY ENTITY NAMES, checked against the " +
    "registry at generation time. `satisfiedBy`, where present, names " +
    "the ones whose rows decide the step; the others name a finding " +
    "and cannot satisfy it. `filter` narrows the step to a subset " +
    "of those rows and its `values` are a disjunction; `intent` names " +
    "the asset intent whose bundle must resolve, `intentBySubjectType` " +
    "names it per kind of subject asked about, and a step on `bundle` " +
    "with neither takes the target's own `intent`. A step whose " +
    "satisfying entities are `bundle` alone is a media step. " +
    "`appliesTo: \"seen\"` marks a step about how characters look, " +
    "assessed only for characters seen at the position. `resolvedBy` " +
    "names the canonical query whose answer at the position decides the " +
    "step: only the rows that answer lets contribute satisfy it. " +
    "`params` " +
    "are §12.9's names, `?` marking an optional one. Rows are narrowed " +
    "as the target query narrows (§12.9.1). `label` is derived " +
    "for display and is the only prose here — a consumer should never " +
    "parse it.",
  $note:
    "Only queries with a generative or pre-flight consumer have a " +
    "rubric. The analytic queries read whatever exists and have no " +
    "readiness semantics of their own beyond the walkable queries they " +
    "are built from — asking Q14 about one is answered by assessing " +
    "those.",
  queryCount: rubrics.length,
  queries: rubrics,
};

const outputs = [
  ["junction-keys.json", junctionDoc],
  ["readiness-rubrics.json", rubricDoc],
];

const check = process.argv.includes("--check");
let stale = [];

for (const [name, doc] of outputs) {
  const path = join(SPEC, name);
  const text = `${JSON.stringify(doc, null, 2)}\n`;
  if (check) {
    let current = "";
    try { current = readFileSync(path, "utf8"); } catch { /* missing */ }
    if (current !== text) stale.push(name);
  } else {
    writeFileSync(path, text, "utf8");
  }
}

if (check) {
  if (stale.length > 0) {
    console.error(`[normative-data] STALE: ${stale.join(", ")}`);
    console.error("  run: npm run emit-normative-data");
    process.exit(1);
  }
  console.log(
    `[normative-data] up to date (${String(junctions.length)} junctions, ` +
    `${String(rubrics.length)} rubrics).`);
} else {
  console.log(
    `[normative-data] wrote ${String(junctions.length)} junctions, ` +
    `${String(rubrics.length)} rubrics.`);
}
